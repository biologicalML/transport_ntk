"""Tables and panels for the camera-ready results.

Reads the CSVs written by `eval/collect_results_*.py` and writes, per family:

  * `<out>/<family>_decrease.tex`  -- decrease vs iteration 0, mean +- stderr
    over fold x seed, in units of 1e-3, one block per dataset;
  * `<out>/<family>_panel.pdf`     -- the metric against the AL iteration, one
    axes per (dataset, budget cell), wrapped `--cols-per-row` to a row;
  * `<out>/<family>_paired_tests.csv` -- tNTK against every other arm, paired
    by seed (folds averaged within a seed first).

The grid (datasets, budget cells, prefixes, arms) comes from
`train/runs/grid.py`, the same table `make_runs.py` builds the run commands
from, so a prefix cannot drift between the two.

Usage:
  python eval/build_summaries.py --family cmonge
  python eval/build_summaries.py --all --out results/summary
"""
import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.lines  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import scipy.stats as stats  # noqa: E402
import seaborn as sns  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "train" / "runs"))
import grid  # noqa: E402

SCALE = 1000.0            # tables are in units of 1e-3
LABEL_SIZE, TITLE_SIZE, TICK_SIZE, LEGEND_SIZE = 14, 15, 13, 12

# Hue names the kernel, linestyle the acquisition rule within it: the tangent
# kernel is red and the kernel it is argued against is blue, matching the 2D
# Gaussian figure. Checked over all pairs with a CVD simulation (Machado 2009,
# severity 1.0): worst protan/deutan dE 11.2, worst normal-vision dE 22.0.
HUE = {
    "random_fixed": "#000000",
    "tntk": "#d62728",
    "ntk": "#1f77b4", "meanvar_ntk": "#1f77b4", "quartile_ntk": "#1f77b4",
    "balsa_emd": "#882255",
}
DASH = {"meanvar_ntk": "--", "quartile_ntk": ":"}
LABEL = {
    "random_fixed": "Random",
    "ntk": "NTK", "meanvar_ntk": "NTK (mean-var)", "quartile_ntk": "NTK (quartile)",
    "balsa_emd": "BALSA-EMD",
    "tntk": "tNTK",
}

FAMILIES = {
    "cmonge": dict(
        spec=grid.CMONGE, metric="mean_sinkhorn div", metric_label="Sinkhorn div.",
        arms=grid.MAIN_ARMS,
        labels={"k562": "K562-Chemical", "bmdm": "BMDM-Genetic"},
    ),
    "cflow": dict(
        spec=grid.CFLOW, metric="sinkhorn_div", metric_label="Sinkhorn div.",
        arms=grid.MAIN_ARMS,
        labels={"radial": "Radial flow", "vanderpol": "Van der Pol oscillator",
                "clinc150": "CLINC 150"},
    ),
    "quantile": dict(
        spec=grid.QUANTILE, metric="w2_distance", metric_label="$W_2$ distance",
        arms=grid.QUANTILE["arms"],
        labels={"sim_mixture": "Simulated Gaussian mixture",
                "temperature": "Temperature", "dewpoint": "Dew Point"},
    ),
}


def csv_path(family, dataset, b0, b, root):
    """Where collect_results_*.py put this cell's metrics."""
    spec = FAMILIES[family]["spec"]
    if family == "quantile":
        mc, wd = spec["datasets"][dataset][b0]
        prefix = spec["prefix"](b0, mc, wd)
    else:
        prefix = spec["prefix"](b0)
    return Path(root) / family / dataset / prefix / f"metrics_{dataset}_size{b}.csv"


def per_fold_seed(df, metric, arms):
    """Mean over conditions, then decrease vs iteration 0, per (arm, fold, seed)."""
    df = df[df["strategy"].isin(arms)].copy()
    per = (df.groupby(["strategy", "fold", "seed", "al_iter"])[metric]
             .mean().reset_index())
    base = (per[per["al_iter"] == 0]
            .set_index(["strategy", "fold", "seed"])[metric].rename("base"))
    per = per.join(base, on=["strategy", "fold", "seed"])
    per["rel"] = per[metric] - per["base"]
    return per


def cell_summary(per, arms):
    """(mean, stderr) of the decrease, averaged over iters >= 1.

    Folds are averaged within a seed first, and the spread is taken across the
    seeds -- the seed is the independent replicate here, the five folds of one
    seed are not. That makes the stderr an n=10 quantity, not n=50, and is the
    same convention the seed-paired tests below use.
    """
    out = {}
    for arm in arms:
        sub = per[(per["strategy"] == arm) & (per["al_iter"] > 0)]
        if not len(sub):
            continue
        by_seed = (sub.groupby(["fold", "seed"])["rel"].mean()
                      .groupby("seed").mean())
        out[arm] = (by_seed.mean() * SCALE,
                    by_seed.std(ddof=1) / np.sqrt(len(by_seed)) * SCALE)
    return out


def latex_table(family, cells, results, out_path):
    f = FAMILIES[family]
    cols = [f"{b0} + {b}" for b0, b in cells]
    lines = [
        "% Generated by eval/build_summaries.py -- do not edit by hand.",
        "\\begin{table}[ht]", "\\centering", "\\small",
        f"\\caption{{{f['metric_label']} decrease vs.\\ iter 0 "
        "(mean across folds per seed, then mean $\\pm$ stderr across seeds; "
        "units $10^{-3}$; columns show $B_0 + B$).}",
        f"\\label{{tab:{family}_decrease}}",
        "\\begin{tabular}{ll" + "c" * len(cols) + "}", "\\toprule",
        "Dataset & Strategy & " + " & ".join(cols) + " \\\\", "\\midrule",
    ]
    for di, (ds, label) in enumerate(f["labels"].items()):
        if di:
            lines.append("\\midrule")
        best = {}
        for col in cols:
            vals = {a: results[(ds, col)][a][0]
                    for a in f["arms"] if (ds, col) in results and a in results[(ds, col)]}
            if vals:
                best[col] = min(vals, key=vals.get)   # most negative = best
        for ai, arm in enumerate(f["arms"]):
            cells_tex = []
            for col in cols:
                r = results.get((ds, col), {}).get(arm)
                if r is None:
                    cells_tex.append("--")
                    continue
                body = f"{r[0]:.2f} \\pm {r[1]:.2f}"
                cells_tex.append(f"$\\mathbf{{{body}}}$" if best.get(col) == arm
                                 else f"${body}$")
            head = (f"\\multirow{{{len(f['arms'])}}}{{*}}{{{label}}}" if ai == 0 else "")
            lines.append(f"{head} & {LABEL[arm]} & " + " & ".join(cells_tex) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    out_path.write_text("\n".join(lines) + "\n")
    print(f"[table]  {out_path}")


def panel(family, cells, raw, out_path, cols_per_row):
    f = FAMILIES[family]
    datasets = list(f["labels"])
    k = min(cols_per_row, len(cells))
    blocks = [list(range(i, min(i + k, len(cells)))) for i in range(0, len(cells), k)]
    n_rows = len(datasets) * len(blocks)
    fig, axes = plt.subplots(n_rows, k, figsize=(3.3 * k, 3.3 * n_rows + 0.7),
                             squeeze=False)
    seen = set()
    for di, ds in enumerate(datasets):
        for bi, block in enumerate(blocks):
            row = di * len(blocks) + bi
            for ax in axes[row, len(block):]:
                ax.axis("off")
            for j, ci in enumerate(block):
                b0, b = cells[ci]
                col = f"{b0} + {b}"
                ax = axes[row, j]
                ax.set_box_aspect(1)
                per = raw.get((ds, col))
                if per is None:
                    ax.text(0.5, 0.5, "no data", ha="center", va="center",
                            transform=ax.transAxes)
                    ax.set_xticks([]); ax.set_yticks([])
                    continue
                for arm in f["arms"]:
                    sub = per[per["strategy"] == arm]
                    if not len(sub):
                        continue
                    seen.add(arm)
                    piv = sub.pivot_table(index=["fold", "seed"], columns="al_iter",
                                          values=f["metric"])
                    mu = piv.mean(axis=0).values
                    se = piv.std(axis=0).values / np.sqrt(piv.shape[0])
                    it = piv.columns.values.astype(int)
                    ax.plot(it, mu, color=HUE[arm], lw=2.5, marker="o", markersize=4,
                            linestyle=DASH.get(arm, "-"), label=LABEL[arm])
                    ax.fill_between(it, mu - se, mu + se, color=HUE[arm],
                                    alpha=0.15, linewidth=0)
                ax.set_xticks(sorted(per["al_iter"].unique().astype(int)))
                ax.set_xlabel("AL iteration", fontsize=LABEL_SIZE)
                ax.set_ylabel((f"{f['labels'][ds]}\n" if j == 0 else "")
                              + f"{f['metric_label']} ($\\downarrow$)",
                              fontsize=LABEL_SIZE)
                ax.set_title(col, fontsize=TITLE_SIZE)
                ax.tick_params(labelsize=TICK_SIZE)
    sns.despine(fig=fig)
    arms = [a for a in f["arms"] if a in seen]
    handles = [matplotlib.lines.Line2D([0], [0], color=HUE[a],
                                       linestyle=DASH.get(a, "-"), lw=2.5)
               for a in arms]
    fig.legend(handles, [LABEL[a] for a in arms], loc="lower center",
               ncol=len(arms), fontsize=LEGEND_SIZE, frameon=False,
               bbox_to_anchor=(0.5, 0.0), handlelength=3.6)
    fig.tight_layout(rect=(0, 0.06, 1, 1))
    for ext in (".pdf", ".png"):
        fig.savefig(out_path.with_suffix(ext), dpi=200, bbox_inches="tight")
        print(f"[panel]  {out_path.with_suffix(ext)}")
    plt.close(fig)


def paired_tests(family, cells, raw, out_path):
    """tNTK vs every other arm, paired by seed (folds averaged within a seed)."""
    f = FAMILIES[family]
    rows = []
    for ds, label in f["labels"].items():
        for b0, b in cells:
            col = f"{b0} + {b}"
            per = raw.get((ds, col))
            if per is None or "tntk" not in set(per["strategy"]):
                continue
            by_seed = (per[per["al_iter"] > 0]
                       .groupby(["strategy", "fold", "seed"])["rel"].mean()
                       .groupby(["strategy", "seed"]).mean().unstack("strategy"))
            for other in [a for a in f["arms"] if a != "tntk" and a in by_seed]:
                pair = by_seed[["tntk", other]].dropna()
                d = (pair["tntk"] - pair[other]) * SCALE
                rows.append(dict(
                    dataset=label, cell=col, other=LABEL[other],
                    tntk=pair["tntk"].mean() * SCALE,
                    other_mean=pair[other].mean() * SCALE,
                    diff_mean=d.mean(), diff_se=d.std(ddof=1) / np.sqrt(len(d)),
                    n_seeds=len(d), tntk_wins_seeds=int((d < 0).sum()),
                    p_t=stats.ttest_rel(pair["tntk"], pair[other]).pvalue,
                    p_wilcoxon=stats.wilcoxon(pair["tntk"], pair[other]).pvalue,
                ))
    pd.DataFrame(rows).to_csv(out_path, index=False)
    print(f"[tests]  {out_path}")


def build(family, root, out, cols_per_row):
    f = FAMILIES[family]
    cells = f["spec"]["cells"]
    raw, results = {}, {}
    for ds in f["labels"]:
        for b0, b in cells:
            path = csv_path(family, ds, b0, b, root)
            if not path.exists():
                print(f"  missing {path}")
                continue
            per = per_fold_seed(pd.read_csv(path), f["metric"], f["arms"])
            raw[(ds, f"{b0} + {b}")] = per
            results[(ds, f"{b0} + {b}")] = cell_summary(per, f["arms"])
    if not raw:
        print(f"[{family}] no inputs found under {root}/{family}; nothing written")
        return
    out.mkdir(parents=True, exist_ok=True)
    latex_table(family, cells, results, out / f"{family}_decrease.tex")
    panel(family, cells, raw, out / f"{family}_panel", cols_per_row)
    paired_tests(family, cells, raw, out / f"{family}_paired_tests.csv")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--family", choices=sorted(FAMILIES))
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--results-root", default="results")
    ap.add_argument("--out", default="results/summary")
    ap.add_argument("--cols-per-row", type=int, default=3)
    args = ap.parse_args()
    fams = sorted(FAMILIES) if args.all else [args.family]
    if fams == [None]:
        ap.error("pass --family or --all")
    for fam in fams:
        build(fam, args.results_root, Path(args.out), args.cols_per_row)


if __name__ == "__main__":
    main()
